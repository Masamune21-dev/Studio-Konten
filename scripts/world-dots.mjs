// Builds the dotted world map for the 3D globe (LandDots in ThreeKitProps.tsx) from Natural Earth
// land polygons (public domain, naturalearthdata.com). Downloaded 9 Oct 2026 with the user's OK:
//   https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson
//   (1,636,166 bytes, sha256 e874b27a51d146452be360cafb3cc50c86001074a67d534113e6534682f9826b)
// The GeoJSON itself is not kept in the project; only the packed dot mask is.
//
// Dots sit in rows `step` degrees apart; each row has round(360·cos(lat)/step) evenly spaced dots,
// so they are about equally far apart everywhere on the sphere. A dot is land if it falls inside a
// land polygon (holes = lakes respected). Islands too small to catch a dot get the dot nearest to
// their middle, so Bali, Lombok, Flores and the like still show.
//
// node scripts/world-dots.mjs <ne_50m_land.geojson> [step=0.7] [out=skill/video-tiktok/assets/template/src/components/worldDots.ts]
import fs from "node:fs";

const [src, stepArg, outArg] = process.argv.slice(2);
if (!src) {
  console.error("Pakai: node scripts/world-dots.mjs <ne_50m_land.geojson> [step] [out.ts]");
  process.exit(1);
}
const step = Number(stepArg ?? 0.7);
const out = outArg ?? "skill/video-tiktok/assets/template/src/components/worldDots.ts";
const geo = JSON.parse(fs.readFileSync(src, "utf8"));

// polygons: [outer, ...holes], each ring [[lon, lat], ...], plus a bbox
const polys = [];
for (const f of geo.features) {
  const g = f.geometry;
  const list = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  for (const rings of list) {
    const xs = rings[0].map((p) => p[0]);
    const ys = rings[0].map((p) => p[1]);
    polys.push({ rings, box: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)] });
  }
}

const inRing = (x, y, ring) => {
  let c = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const inPoly = (x, y, p) => x >= p.box[0] && x <= p.box[2] && y >= p.box[1] && y <= p.box[3] && inRing(x, y, p.rings[0]) && !p.rings.slice(1).some((h) => inRing(x, y, h));

// the grid
const rows = Math.round(180 / step);
const grid = []; // { lat, n }
let total = 0;
for (let i = 0; i < rows; i++) {
  const lat = -90 + (i + 0.5) * (180 / rows);
  const n = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / step));
  grid.push({ lat, n, start: total });
  total += n;
}
const lonOf = (row, j) => -180 + ((j + 0.5) * 360) / row.n;
const bits = new Uint8Array(Math.ceil(total / 8));
const set = (k) => (bits[k >> 3] |= 1 << (k & 7));
const get = (k) => (bits[k >> 3] >> (k & 7)) & 1;

let land = 0;
const hit = new Set();
for (const row of grid)
  for (let j = 0; j < row.n; j++) {
    const lon = lonOf(row, j);
    const p = polys.findIndex((q) => inPoly(lon, row.lat, q));
    if (p >= 0) {
      set(row.start + j);
      hit.add(p);
      land++;
    }
  }

// small islands that no dot landed in: light the dot nearest to the middle of their box
let islands = 0;
polys.forEach((p, idx) => {
  if (hit.has(idx)) return;
  const area = (p.box[2] - p.box[0]) * (p.box[3] - p.box[1]);
  if (area < 0.02) return; // rocks and reefs
  const lat = (p.box[1] + p.box[3]) / 2;
  const lon = (p.box[0] + p.box[2]) / 2;
  const i = Math.min(rows - 1, Math.max(0, Math.floor((lat + 90) / (180 / rows))));
  const row = grid[i];
  const j = ((Math.floor(((lon + 180) / 360) * row.n) % row.n) + row.n) % row.n;
  if (!get(row.start + j)) {
    set(row.start + j);
    islands++;
    land++;
  }
});

const b64 = Buffer.from(bits).toString("base64");
const ts = `// Dotted world map for LandDots (ThreeKitProps.tsx). GENERATED by scripts/world-dots.mjs from
// Natural Earth 1:50m land (public domain, naturalearthdata.com); do not edit by hand.
// Rows are ${step}° apart from the south pole up; row i holds round(360·cos(lat)/${step}) dots starting
// at lon −180 + half a gap. One bit per dot (1 = land), least significant bit first.
// ${land} land dots of ${total}.
export const WORLD_DOTS = { step: ${step}, rows: ${rows}, count: ${total}, bits: "${b64}" };
`;
fs.writeFileSync(out, ts);
console.log(`step ${step}°, ${rows} rows, ${total} dots, land ${land} (${islands} small islands added), ${b64.length} base64 chars → ${out}`);
